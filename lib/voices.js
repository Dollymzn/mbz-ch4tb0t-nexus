// Linha compacta pro prompt: "Nome — descrição (id)"
function voiceCatalogText() {
  return VOICES.map(v => `- ${v.name} — ${v.desc || 'sem descrição'} [id: ${v.id}]`).join('\n');
}
function findVoice(nameOrId) {
  const q = String(nameOrId || '').trim().toLowerCase();
  if (!q) return null;
  return VOICES.find(v => v.id.toLowerCase() === q) || VOICES.find(v => v.name.toLowerCase() === q) || VOICES.find(v => v.name.toLowerCase().startsWith(q)) || null;
}
